console.log(`body byte-identical to source: ${tailMatches && misaligned === 0 ? 'YES' : 'NO'} (misaligned lines: ${misaligned})`);
console.log(`verbatim body starts at this file's line ${realStart + 1} = source line 1`);
console.log(`source sha256 ${sha256(srcBuf)}`);
console.log(`header rows: ${rows.length} discrepancies`);
if (!(tailMatches && misaligned === 0)) process.exitCode = 1;
