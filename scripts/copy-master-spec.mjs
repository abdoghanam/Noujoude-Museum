let out = header.join('\n') + '\n' + body;

// The offset is measured from the emitted text and then written into that same text,
// so a later edit to this header cannot leave a stale "+N lines" claim behind: the
// placeholder is resolved after the geometry is known, and the alignment is re-checked
// on the file that was actually written.
const probe = bodyLines.slice(0, 3).join('\n');
const bodyStart = out.split(/\r?\n/).findIndex(
  (l, i, all) => all.slice(i, i + 3).join('\n') === probe,
);
if (bodyStart < 1) {
  console.error('could not locate the verbatim body inside the generated file');
  process.exit(1);
}
out = out.replace(
  '__OFFSET__',
  `source line N = line N + ${bodyStart} of this file (measured on write)`,
);
fs.writeFileSync(OUT, out, 'utf8');

const writtenBuf = fs.readFileSync(OUT);
const written = writtenBuf.toString('utf8');
const wl = written.split(/\r?\n/);
const realStart = wl.findIndex((l, i, all) => all.slice(i, i + 3).join('\n') === probe);
let misaligned = 0;
for (let n = 0; n < bodyLines.length; n++) if (wl[realStart + n] !== bodyLines[n]) misaligned++;
const tailMatches = written.endsWith(body);

// Both figures below were wrong in the version this replaced, and they were wrong in opposite
// directions — too small and too large — which is why nobody challenged either one.
//   • `${written.length} bytes` reported a **string**'s UTF-16 code units. Every typographic
//     character this specification carries (’ “ ” — ≤) is one code unit and three UTF-8 bytes, so
//     the label was false by 1,538 on the 1 Nov 2026 generation (255,561 reported / 257,099 on
//     disk). Measured against the disk instead. The error is not body-dependent: the provenance
//     header this script writes is itself full of em dashes, so a code-unit count is wrong even
//     for a pure-ASCII source.
//   • `${wl.length} lines` counted the empty element `split` produces after a final newline
//     (4,070 reported / 4,069 real). The same off-by-one is already handled for the source body
//     above, and the generated copy ends the same way.
// Guarded by scripts/tests/copy-master-spec-output.test.mjs, which computes the truth by counting
// newline characters rather than splitting, so it cannot restate this implementation. Defect record:
// docs/TEST_AND_RELEASE_REPORT.md §2.2.
const hasFinalNewline = written.endsWith('\n');
const writtenLines = hasFinalNewline ? wl.length - 1 : wl.length;

